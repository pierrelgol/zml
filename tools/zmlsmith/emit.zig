//! Turns a program into a standalone Zig test calling the ZML API, with the reference
//! outputs embedded. Reduced failures become regression tests this way.

const std = @import("std");

const zml = @import("zml");

const ir = @import("ir.zig");
const kit = @import("kit.zig");
const ops = @import("ops.zig");
const runner = @import("runner.zig");
const Value = @import("Value.zig");
const sharding = @import("ops/sharding.zig");

fn printBytes(w: *std.Io.Writer, bytes: []const u8) !void {
    try w.writeAll("{");
    for (bytes, 0..) |b, i| {
        if (i % 24 == 0) try w.writeAll("\n        ");
        try w.print("{d},", .{b});
    }
    try w.writeAll("\n    }");
}

/// Writes one `const xN = ...;` line per node of region `scope` in [start, end).
pub fn emitScope(prog: *const ir.Program, w: *std.Io.Writer, names: []const []const u8, start: u32, end: u32, scope: u32, indent: usize) std.Io.Writer.Error!void {
    for (start..end) |i| {
        const n = &prog.nodes.items[i];
        if (n.scope != scope or ops.isArgument(n.op) or n.op == .param) continue;
        switch (n.op) {
            inline else => |_, tag| {
                const I = @field(ops.impls, @tagName(tag));
                if (comptime @hasDecl(I, "emitCtl")) {
                    try I.emitCtl(prog, @intCast(i), w, names, indent);
                } else {
                    var ins: [ir.max_operands][]const u8 = undefined;
                    var shapes: [ir.max_operands]zml.Shape = undefined;
                    for (n.inputs.slice(), 0..) |in, j| {
                        ins[j] = names[in];
                        shapes[j] = prog.nodes.items[in].shape;
                    }
                    kit.emit_shapes = shapes[0..n.inputs.len];
                    for (0..indent) |_| try w.writeByte(' ');
                    try w.print("const {s} = ", .{names[i]});
                    try ops.emit(n, w, ins[0..n.inputs.len]);
                    try w.writeAll(";\n");
                }
            },
        }
        // Nodes that end up unused (dead region code, dropped outputs) must still compile.
        for (0..indent) |_| try w.writeByte(' ');
        try w.print("_ = &{s};\n", .{names[i]});
    }
}

pub fn zigTest(allocator: std.mem.Allocator, prog: *const ir.Program) ![]const u8 {
    const values = try runner.reference(allocator, prog);
    const args = try prog.argumentNodes(allocator);
    var out: std.Io.Writer.Allocating = .init(allocator);
    const w = &out.writer;

    try w.print(
        \\const std = @import("std");
        \\const zml = @import("zml");
        \\
        \\// Generated by zmlsmith from seed {d}.
        \\test "zmlsmith seed {d}" {{
        \\    const platform = zml.testing.env();
        \\    const allocator = std.testing.allocator;
        \\    const io = std.testing.io;
        \\
        \\    const Local = struct {{
        \\        fn forward(
    , .{ prog.seed, prog.seed });
    for (args, 0..) |id, i| try w.print("{s}x{d}: zml.Tensor", .{ if (i > 0) ", " else "", id });
    try w.print(") [{d}]zml.Tensor {{\n", .{prog.outputs.items.len});

    var names = try allocator.alloc([]const u8, prog.nodes.items.len);
    for (0..prog.nodes.items.len) |i| names[i] = try std.fmt.allocPrint(allocator, "x{d}", .{i});
    try emitScope(prog, w, names, 0, @intCast(prog.nodes.items.len), 0, 12);
    // Arguments that aren't used would be reported by the Zig compiler.
    for (args) |id| {
        var used = false;
        for (prog.nodes.items) |n| for (n.inputs.slice()) |in| {
            if (in == id) used = true;
        };
        for (prog.outputs.items) |o| if (o == id) {
            used = true;
        };
        if (!used) try w.print("            _ = x{d};\n", .{id});
    }
    try w.writeAll("            return .{ ");
    for (prog.outputs.items, 0..) |o, i| try w.print("{s}x{d}", .{ if (i > 0) ", " else "", o });
    try w.writeAll(" };\n        }\n    };\n\n");

    if (prog.sharded) {
        // The `data` x `model` mesh over all devices; one name per test as registration is
        // global to the platform.
        try w.print("    const mesh = try @constCast(platform).registerSharding(\"zmlsmith_{d}\", .mesh(.{{ .data = .low_bandwidth, .model = .high_bandwidth }}));\n", .{prog.seed});
    }
    for (args) |id| {
        try w.print("    const x{d}: zml.Tensor = .fromShape(", .{id});
        try kit.printShapeLiteral(w, prog.nodes.items[id].shape);
        if (prog.sharded and prog.shard_args) {
            const sh = sharding.argumentShape(prog.nodes.items[id].shape);
            for (0..sh.rank()) |ax| if (sh.partition(ax) == .axis) {
                try w.print(".withPartitioning(.{{ .{s} = .data }})", .{kit.tagLiteral(sh.tag(ax))});
            };
        }
        try w.writeAll(");\n");
    }
    try w.writeAll("    var exe = try zml.module.compile(allocator, io, Local.forward, .{ ");
    for (args, 0..) |id, i| try w.print("{s}x{d}", .{ if (i > 0) ", " else "", id });
    try w.print(" }}, platform, .{{{s}}});\n    defer exe.deinit();\n\n", .{if (prog.sharded) " .shardings = &.{mesh} " else ""});
    // The shapes ZML is documented to return, tags included.
    for (prog.outputs.items, 0..) |o, i| {
        try w.writeAll("    try zml.testing.expectEqualShapes(");
        try kit.printShapeLiteral(w, prog.nodes.items[o].shape);
        try w.print(", exe.output_shapes[{d}]);\n", .{i});
    }
    try w.writeAll("\n");

    for (args) |id| {
        try w.print("    var b{d}: zml.Buffer = try .fromBytes(io, platform, x{d}.shape(), {s}, &[_]u8", .{ id, id, if (prog.sharded) "mesh" else ".replicated" });
        try printBytes(w, values[id].bytes);
        try w.print(");\n    defer b{d}.deinit();\n", .{id});
    }
    // Without arguments the Bufferized argument tuple is void.
    try w.writeAll("    var res = try zml.testing.autoCall(allocator, io, &exe, Local.forward, ");
    if (args.len == 0) try w.writeAll("{}") else {
        try w.writeAll(".{ ");
        for (args, 0..) |id, i| try w.print("{s}b{d}", .{ if (i > 0) ", " else "", id });
        try w.writeAll(" }");
    }
    try w.writeAll(");\n    defer for (&res) |*r| r.deinit();\n\n");

    for (prog.outputs.items, 0..) |o, i| {
        const v = values[o];
        // Slice.init doesn't check alignment, but reading the items does.
        try w.writeAll("    {\n        const expected_data align(16) = [_]u8");
        try printBytes(w, v.bytes);
        try w.writeAll(";\n        const expected: zml.Slice = .init(");
        try kit.printShapeLiteral(w, v.shape);
        try w.writeAll(", @as([]const u8, &expected_data));\n");
        if (Value.isStorage(v.dtype()) and Value.isFloat(v.dtype()) and v.err > 0) {
            // Rounded f8/f4 values: zml.testing can't compare these dtypes and zml.floats
            // decodes some of them wrong, so only the shape is checked.
            try w.print("        _ = expected;\n        _ = res[{d}];\n", .{i});
        } else if (v.errs != null and Value.isFloat(v.dtype()) and v.count() > 0 and !Value.isStorage(v.dtype())) {
            // Per element bounds, checked like runner.compare: 0 means bit exact, sign of
            // zero included.
            const conv = if (v.dtype() == .bf16) ".toF32()" else "";
            try w.writeAll("        const errs = [_]f64{ ");
            for (v.errs.?, 0..) |x, j| try w.print("{s}{e}", .{ if (j > 0) ", " else "", x });
            try w.writeAll(" };\n");
            try w.print("        const got = try res[{d}].toSliceAlloc(allocator, io);\n        defer got.free(allocator);\n", .{i});
            try w.print("        for (expected.constItems({s}), got.constItems({s}), errs) |e_, g_, b| {{\n            const e: f64 = @floatCast(e_{s});\n            const g: f64 = @floatCast(g_{s});\n", .{ zigFloat(v.dtype()), zigFloat(v.dtype()), conv, conv });
            try w.writeAll("            if (std.math.isNan(e)) {\n                try std.testing.expect(std.math.isNan(g));\n            } else if (!std.math.isFinite(e) or b == 0) {\n                try std.testing.expect(e == g and std.math.signbit(e) == std.math.signbit(g));\n            } else try std.testing.expect(@abs(e - g) <= b);\n        }\n");
        } else if (v.allow_inf and v.count() > 0 and !Value.isStorage(v.dtype())) {
            // Special values: NaN matches any NaN (payloads differ), infinities exactly,
            // finite values within the bound.
            const conv = if (v.dtype() == .bf16) ".toF32()" else "";
            try w.print("        const got = try res[{d}].toSliceAlloc(allocator, io);\n        defer got.free(allocator);\n", .{i});
            try w.print("        for (expected.constItems({s}), got.constItems({s})) |e_, g_| {{\n            const e: f64 = @floatCast(e_{s});\n            const g: f64 = @floatCast(g_{s});\n", .{ zigFloat(v.dtype()), zigFloat(v.dtype()), conv, conv });
            try w.print("            try std.testing.expect((std.math.isNan(e) and std.math.isNan(g)) or e == g or @abs(e - g) <= {e});\n        }}\n", .{v.err});
        } else if (!Value.isFloat(v.dtype()) or v.allow_inf or v.count() == 0 or Value.isStorage(v.dtype())) {
            // zml.testing.expectClose panics on bool, rejects any infinity, even an expected
            // one, fails on empty tensors (NaN close fraction) and hits `unreachable` for
            // f4e2m1, f8e3m4, f8e4m3 and f8e8m0: compare the bytes.
            try w.print("        const got = try res[{d}].toSliceAlloc(allocator, io);\n        defer got.free(allocator);\n        try std.testing.expectEqualSlices(u8, expected.constData(), got.constData());\n", .{i});
        } else if (v.err == 0) {
            try w.print("        try zml.testing.expectClose(io, expected, res[{d}], .exact_match);\n", .{i});
        } else {
            const tol: f64 = 2 * v.err + 2 * Value.eps(v.dtype()) * v.maxAbs();
            try w.print("        try zml.testing.expectClose(io, expected, res[{d}], .{{ .absolute_tolerance = {e}, .relative_tolerance = {e}, .minimum_close_fraction = 1 }});\n", .{ i, tol, 2 * Value.eps(v.dtype()) });
        }
        try w.writeAll("    }\n");
    }
    try w.writeAll("}\n");
    return out.written();
}

fn zigFloat(dt: zml.DataType) []const u8 {
    return switch (dt) {
        .bf16 => "zml.floats.BFloat16",
        .f16 => "f16",
        .f32 => "f32",
        else => "f64",
    };
}
